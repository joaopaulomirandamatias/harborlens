"""Verify reviewer attestations against a separately pinned Ed25519 trust root.

SPEC-003 / BR-015, BR-016. Private keys are never loaded or generated by
production HarborLens code. A caller must provide an externally trusted public
key, its independently pinned SHA-256 fingerprint, and reviewer identity.
"""
from __future__ import annotations

import base64
import binascii
import hashlib
import hmac
import json
import re
from pathlib import Path

MAX_PUBLIC_KEY_BYTES = 8192
_HEX64 = re.compile(r"^[0-9a-f]{64}$")
# Domain separator so this signature cannot be replayed as another signed object.
# Signatures from 0.2.0.dev4 covered the JSON body only and no longer verify.
REVIEW_SIGNATURE_DOMAIN = "harborlens.publication-review.v1\n"


class ReviewSignatureError(ValueError):
    """A review cannot be authenticated under the specified trust root."""


def _crypto():
    try:
        from cryptography.exceptions import InvalidSignature
        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    except ImportError as exc:
        raise ReviewSignatureError(
            "Install the release extra for Ed25519 verification"
        ) from exc
    return InvalidSignature, serialization, Ed25519PublicKey


def public_key_fingerprint(public_key_path):
    """Return the canonical SPKI DER SHA-256 of a local Ed25519 public key."""
    _, serialization, Ed25519PublicKey = _crypto()
    try:
        with Path(public_key_path).open("rb") as handle:
            raw = handle.read(MAX_PUBLIC_KEY_BYTES + 1)
        if len(raw) > MAX_PUBLIC_KEY_BYTES:
            raise ReviewSignatureError("Public key file exceeds byte limit")
        key = serialization.load_pem_public_key(raw)
    except (OSError, ValueError, TypeError) as exc:
        if isinstance(exc, ReviewSignatureError):
            raise
        raise ReviewSignatureError("Invalid or missing reviewer public key") from exc
    if not isinstance(key, Ed25519PublicKey):
        raise ReviewSignatureError("Only Ed25519 public keys are supported")
    canonical = key.public_bytes(
        encoding=serialization.Encoding.DER,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    return key, hashlib.sha256(canonical).hexdigest()


def _fingerprints_equal(left, right):
    """Compare public fingerprints without an early content mismatch return."""
    if not isinstance(left, str) or not isinstance(right, str) or len(left) != len(right):
        return False
    return hmac.compare_digest(left, right)


def review_message(review):
    """Domain-separated canonical claims; excludes only the detached signature bytes."""
    if not isinstance(review, dict) or "signature_b64" not in review:
        raise ReviewSignatureError("Signed review object is required")
    claims = {name: value for name, value in review.items() if name != "signature_b64"}
    try:
        body = json.dumps(claims, sort_keys=True, separators=(",", ":"),
                          ensure_ascii=True, allow_nan=False) + "\n"
    except ValueError as exc:
        raise ReviewSignatureError("Signed review contains a non-finite number") from exc
    return (REVIEW_SIGNATURE_DOMAIN + body).encode("ascii")


def verify_review_signature(review, *, trusted_public_key,
                            expected_public_key_sha256, expected_reviewer_id):
    """Reject untrusted keys, mismatched identities and altered claims."""
    if (not isinstance(expected_public_key_sha256, str)
            or not _HEX64.fullmatch(expected_public_key_sha256)
            or not isinstance(expected_reviewer_id, str)
            or not expected_reviewer_id):
        raise ReviewSignatureError("External reviewer trust configuration is required")
    if (review.get("signature_algorithm") != "Ed25519"
            or review.get("reviewer_id") != expected_reviewer_id):
        raise ReviewSignatureError("Reviewer identity or algorithm is not trusted")
    key, actual_hash = public_key_fingerprint(trusted_public_key)
    if (not _fingerprints_equal(expected_public_key_sha256, actual_hash)
            or not _fingerprints_equal(review.get("public_key_sha256"), actual_hash)):
        raise ReviewSignatureError("Reviewer key fingerprint does not match trust anchor")
    signature = review.get("signature_b64")
    if not isinstance(signature, str) or len(signature) > 128:
        raise ReviewSignatureError("Missing or malformed Ed25519 signature")
    try:
        decoded = base64.b64decode(signature, validate=True)
    except (ValueError, binascii.Error) as exc:
        raise ReviewSignatureError("Invalid Ed25519 signature encoding") from exc
    if len(decoded) != 64:
        raise ReviewSignatureError("Ed25519 signatures must contain 64 bytes")
    invalid_signature, _, _ = _crypto()
    try:
        key.verify(decoded, review_message(review))
    except invalid_signature as exc:
        raise ReviewSignatureError("Reviewer signature is invalid") from exc
    return actual_hash
